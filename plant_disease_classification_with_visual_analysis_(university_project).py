img_path = ''
for class_folder in os.listdir(dataset_path):
    class_folder_path = os.path.join(dataset_path, class_folder)
    if os.path.isdir(class_folder_path):
        images_in_folder = [f for f in os.listdir(class_folder_path) if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.bmp'))]
        if images_in_folder:
            img_path = os.path.join(class_folder_path, images_in_folder[0])
            test_image_found = True
            break

if not test_image_found:
    raise FileNotFoundError("No image found in the dataset for testing. Please ensure the 'PlantVillage' directory contains image files.")

print(f"Using test image: {img_path}")

# Display the chosen test image
plt.figure(figsize=(6,6))
plt.imshow(plt.imread(img_path))
plt.title(f"Test Image: {os.path.basename(img_path)}")
plt.axis('off')
plt.show()

# Load image
img = image.load_img(
    img_path,
    target_size=(128, 128)
)

# Convert image to array
img_array = image.img_to_array(img)

# Normalize image
img_array = img_array / 255.0

# Expand dimensions
img_array = np.expand_dims(img_array, axis=0)

# Prediction
prediction = model.predict(img_array)

# Class Names
class_names = list(train_data.class_indices.keys())

# Final Output
predicted_class = class_names[np.argmax(prediction)]

print("===================================")
print("Prediction Result")
print("===================================")

print("Predicted Disease:", predicted_class)