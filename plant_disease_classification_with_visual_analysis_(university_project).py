# 1. Import Libraries
import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D
import matplotlib.pyplot as plt
import numpy as np
import os

# ============================================
# 2. Dataset Preparation
# ============================================

# Dataset Path
dataset_path = "PlantVillage"

# ============================================
# 3. Count Healthy & Diseased Images
# ============================================

healthy_count = 0
disease_count = 0

# Loop through dataset folders
for folder in os.listdir(dataset_path):

    folder_path = os.path.join(dataset_path, folder)

    # Count image files
    image_count = len(os.listdir(folder_path))

    # Check Healthy or Diseased
    if "healthy" in folder.lower():
        healthy_count += image_count
    else:
        disease_count += image_count

# Total Images
total_images = healthy_count + disease_count

# Percentage Calculation
healthy_percentage = (healthy_count / total_images) * 100
disease_percentage = (disease_count / total_images) * 100

# Print Results
print("===================================")
print("Dataset Information")
print("===================================")

print(f"Total Images: {total_images}")

print(f"Healthy Leaf Images: {healthy_count}")
print(f"Healthy Percentage: {healthy_percentage:.2f}%")

print(f"Diseased Leaf Images: {disease_count}")
print(f"Diseased Percentage: {disease_percentage:.2f}%")

# ============================================
# 4. Image Data Generator
# ============================================

train_datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2
)

# Training Data
train_data = train_datagen.flow_from_directory(
    dataset_path,
    target_size=(128, 128),
    batch_size=32,
    class_mode='categorical',
    subset='training'
)

# Validation Data
validation_data = train_datagen.flow_from_directory(
    dataset_path,
    target_size=(128, 128),
    batch_size=32,
    class_mode='categorical',
    subset='validation'
)

# ============================================
# 5. Load Pretrained Model
# ============================================

base_model = MobileNetV2(
    weights='imagenet',
    include_top=False,
    input_shape=(128, 128, 3)
)

# Freeze pretrained layers
base_model.trainable = False

# ============================================
# 6. Build Deep Learning Model
# ============================================

model = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    Dense(128, activation='relu'),
    Dense(train_data.num_classes, activation='softmax')
])

# ============================================
# 7. Compile Model
# ============================================

model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# ============================================
# 8. Train Model
# ============================================

history = model.fit(
    train_data,
    validation_data=validation_data,
    epochs=5
)

# ============================================
# 9. Accuracy Graph
# ============================================

plt.figure(figsize=(8,5))

plt.plot(
    history.history['accuracy'],
    label='Training Accuracy'
)

plt.plot(
    history.history['val_accuracy'],
    label='Validation Accuracy'
)

plt.title("Model Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()

plt.show()

# ============================================
# 10. Loss Graph
# ============================================

plt.figure(figsize=(8,5))

plt.plot(
    history.history['loss'],
    label='Training Loss'
)

plt.plot(
    history.history['val_loss'],
    label='Validation Loss'
)

plt.title("Model Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()

plt.show()

